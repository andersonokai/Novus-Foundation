const blogPosts = Object.entries(siteContent)
  .filter(([, item]) => item.section === "story" && item.published === true)
  .map(([slug, item]) => ({
    slug,
    title: item.title,
    image: item.heroImage,
    date: item.date,
    author: item.author || "Novus Foundation"
  }));

function getSelectedItem() {
  const params = new URLSearchParams(window.location.search);
  const slug = params.get('slug');
  const selected = slug && siteContent[slug] ? siteContent[slug] : siteContent['digital-launchpad'];
  return selected;
}

function renderDetailPage() {
  if (!document.getElementById('detail-title')) return;

  const item = getSelectedItem();
  if (!item) return;

  const titleNode = document.getElementById('detail-title');
  const dateNode = document.getElementById('detail-date');
  const locationNode = document.getElementById('detail-location');
  const timeNode = document.getElementById('detail-time');
  const summaryNode = document.getElementById('detail-summary');
  const imageNode = document.getElementById('detail-image');
  const bodyNode = document.getElementById('detail-body');
  const tagsNode = document.getElementById('detail-tags');

  if (titleNode) titleNode.textContent = item.title;
  if (dateNode) dateNode.textContent = item.date;
  if (locationNode) locationNode.textContent = item.location;
  if (timeNode && item.time) timeNode.textContent = item.time;
  if (summaryNode) summaryNode.textContent = item.summary;
  if (imageNode) imageNode.src = item.heroImage;
  if (bodyNode) bodyNode.innerHTML = item.body.join('');
  if (tagsNode) {
    tagsNode.innerHTML = item.tags.map((tag) => `<a href="#" class="tag-cloud-link">${tag}</a>`).join('');
  }

  const pageTitle = document.querySelector('title');
  if (pageTitle) {
    pageTitle.textContent = `${item.title} | Novus Foundation`;
  }
}

function renderBlogPost(post) {
  const article = document.createElement('article');
  article.className = 'block-21 mb-4 d-flex';
  article.innerHTML = `
    <a class="blog-img mr-4" href="blog-single.html?slug=${encodeURIComponent(post.slug)}"
       style="background-image: url('${post.image}');" aria-label="${post.title}"></a>
    <div class="text">
      <h3 class="heading"><a href="blog-single.html?slug=${encodeURIComponent(post.slug)}">${post.title}</a></h3>
      <div class="meta">
        <div><span class="icon-calendar"></span> ${post.date}</div>
        <div><span class="icon-person"></span> ${post.author}</div>
      </div>
    </div>
  `;
  return article;
}

function renderRecentBlog() {
  const sections = document.querySelectorAll('[data-recent-blog]');

  sections.forEach((section) => {
    if (!blogPosts.length) {
      section.hidden = true;
      return;
    }

    section.hidden = false;
    const posts = section.querySelector('[data-blog-posts]');
    if (posts) {
      const renderedPosts = blogPosts.slice(0, 2).map(renderBlogPost);
      if (section.classList.contains('recent-blog-section')) {
        renderedPosts.forEach((post) => post.classList.add('col-md-6'));
      }
      posts.replaceChildren(...renderedPosts);
    }
  });

  document.querySelectorAll('footer .ftco-footer-widget').forEach((widget) => {
    const heading = widget.querySelector('.ftco-heading-2');
    if (!heading || !/Recent (Blog|Stories)/i.test(heading.textContent.trim())) return;

    if (!blogPosts.length) {
      widget.parentElement.hidden = true;
      return;
    }

    widget.replaceChildren();
    const title = document.createElement('h2');
    title.className = 'ftco-heading-2';
    title.textContent = 'Recent Blog';
    widget.appendChild(title);
    blogPosts.slice(0, 2).forEach((post) => widget.appendChild(renderBlogPost(post)));
  });
}

document.addEventListener('DOMContentLoaded', () => {
  renderDetailPage();
  renderRecentBlog();
});
